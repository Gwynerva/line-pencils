"""Exact (computer-algebra) proof that a given linear space has no realization by points of RP^2
with EXACTLY its collinearities.

Method.  Choose four points of the space, no three collinear in it, as the projective frame
    F0 = (1:0:0), F1 = (0:1:0), F2 = (0:0:1), F3 = (1:1:1).
If F0 and F1 lie in a common block B, the other points of B lie on the line z = 0 and get coordinates
(q : 1 : 0); every other point gets (x : y : 1).  (In a realization no point outside B lies on the line
F0F1, and no point of B equals F0, so these charts cover every realization once the frame is fixed; the
projective group acts transitively on frames.)  Collinearity of three points is the vanishing of a 3x3
determinant, a polynomial in the unknowns; let I be the ideal generated by the determinants of all triples
inside blocks.  Every realization of the space (with its collinearities, possibly more) is a point of V(I).

A realization with EXACTLY the given collinearities is a point of V(I) where the determinant d_T of every
non-collinear triple T is non-zero.  If for some T the polynomial d_T vanishes on all of V(I) (d_T is in
the radical of I), then no such realization exists, over C and a fortiori over R.  By Rabinowitsch's trick
d_T is in the radical of I  iff  the ideal I + (t*d_T - 1) is the unit ideal, which a Groebner basis decides.

The candidates T are taken from numerical least-squares solutions (the triples that collapse there); the
proof itself does not depend on the numerics.

usage: python scripts/algebraic_nonrealizability.py N "b1 b2 ..." [--candidates K]
output: PROVED (with the triple T and the Groebner statement) or UNDECIDED.
"""
import argparse, itertools, os, sys, time
import numpy as np
import sympy as sp
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
from realize import collinear_triples, numeric_realization


def setup(n, blocks):
    col = collinear_triples(blocks)
    # frame: prefer F0, F1 inside the largest block (so the big block becomes the line z = 0)
    big = max(blocks, key=len)
    frame = None
    for f0, f1 in itertools.combinations(big, 2):
        for f2, f3 in itertools.combinations([p for p in range(n) if p not in (f0, f1)], 2):
            q = (f0, f1, f2, f3)
            if all(tuple(sorted(t)) not in col for t in itertools.combinations(q, 3)):
                frame = q; break
        if frame: break
    if frame is None:
        raise SystemExit("no frame found")
    f0, f1, f2, f3 = frame
    P = {f0: sp.Matrix([1, 0, 0]), f1: sp.Matrix([0, 1, 0]), f2: sp.Matrix([0, 0, 1]), f3: sp.Matrix([1, 1, 1])}
    vars_ = []
    blk01 = next(B for B in blocks if f0 in B and f1 in B)
    for p in range(n):
        if p in P:
            continue
        if p in blk01:
            q = sp.Symbol("q%d" % p); vars_.append(q); P[p] = sp.Matrix([q, 1, 0])
        else:
            x, y = sp.symbols("x%d y%d" % (p, p)); vars_ += [x, y]; P[p] = sp.Matrix([x, y, 1])
    def det(t):
        return sp.expand(sp.Matrix.hstack(P[t[0]], P[t[1]], P[t[2]]).det())
    eqs = []
    for B in blocks:
        for t in itertools.combinations(sorted(B), 3):
            d = det(t)
            if d != 0:
                eqs.append(d)
    eqs = list(dict.fromkeys(eqs))
    noncol = [t for t in itertools.combinations(range(n), 3) if t not in col]
    return frame, P, vars_, eqs, noncol, det


def candidate_triples(n, blocks, vars_, eqs, noncol, det, k=8, starts=60, seed=0):
    """Numerically sample V(I) over C (real and complex starts) and return a small family of non-collinear
    triples such that every sampled solution has at least one of them collinear (greedy hitting set).
    The family is only a guess for the exact test; nothing depends on the numerics being complete."""
    from scipy.optimize import least_squares
    f = sp.lambdify(vars_, eqs, "numpy")
    J = sp.lambdify(vars_, sp.Matrix(eqs).jacobian(vars_), "numpy")
    nd = sp.lambdify(vars_, [det(T) for T in noncol], "numpy")
    m = len(vars_)
    def res(z):
        v = z[:m] + 1j * z[m:]; r = np.array(f(*v), dtype=complex); return np.concatenate([r.real, r.imag])
    def jac(z):
        v = z[:m] + 1j * z[m:]; Jm = np.array(J(*v), dtype=complex)
        return np.block([[Jm.real, -Jm.imag], [Jm.imag, Jm.real]])
    rng = np.random.default_rng(seed)
    collapsed = []
    for s in range(starts):
        z0 = rng.normal(size=2 * m)
        if s % 2 == 0:
            z0[m:] = 0                      # real start (solutions tend to stay real)
        r = least_squares(res, z0, jac=jac, xtol=1e-15, ftol=1e-15, gtol=1e-15, max_nfev=2000)
        v = r.x[:m] + 1j * r.x[m:]
        if np.max(np.abs(np.array(f(*v), dtype=complex))) > 1e-9:
            continue
        scale = max(1.0, np.max(np.abs(v))) ** 3
        ds = np.abs(np.array(nd(*v), dtype=complex)) / scale
        S = frozenset(T for T, d in zip(noncol, ds) if d < 1e-7)
        if S:
            collapsed.append(S)
    chosen = []
    remaining = list(collapsed)
    while remaining and len(chosen) < k:
        cnt = {}
        for S in remaining:
            for T in S:
                cnt[T] = cnt.get(T, 0) + 1
        T = max(cnt, key=cnt.get)
        chosen.append(T)
        remaining = [S for S in remaining if T not in S]
    return chosen, len(collapsed), len(remaining)


def prove(n, blocks, k=6, verbose=True):
    t0 = time.time()
    frame, P, vars_, eqs, noncol, det = setup(n, blocks)
    if verbose:
        print("frame", frame, "unknowns", len(vars_), "equations", len(eqs), flush=True)
    cands, nsol, uncovered = candidate_triples(n, blocks, vars_, eqs, noncol, det, k=k)
    if verbose:
        print("numerical solutions sampled:", nsol, "; hitting set of collapsing triples:", cands, "; uncovered:", uncovered, flush=True)
    t = sp.Symbol("t")
    # V(I) may have several components, each with its own extra collinearity: test whether the PRODUCT of the
    # candidate determinants vanishes on V(I), i.e. whether every solution has at least one of the collapses.
    # (A single triple suffices when V(I) is irreducible; the product handles the general case.)
    tried = []
    g = sp.Integer(1)
    for T in cands:
        dT = det(T)
        if dT == 0:
            continue
        tried.append(T)
        g = sp.expand(g * dT)
        G = sp.groebner(eqs + [t * g - 1], *vars_, t, order="grevlex")
        unit = (len(G.exprs) == 1 and G.exprs[0] == 1)
        if verbose:
            print("  product over triples", tried, "in the radical:", unit, "(%.0fs)" % (time.time() - t0), flush=True)
        if unit:
            return {"status": "PROVED", "triples": [list(x) for x in tried], "frame": list(frame),
                    "unknowns": [str(v) for v in vars_], "equations": [str(e) for e in eqs],
                    "statement": "the ideal generated by the equations together with t*g-1, g = product of the determinants of the listed triples, is the unit ideal (Groebner basis = [1]); hence every point of V(I) has one of these triples collinear",
                    "time": round(time.time() - t0, 1)}
    return {"status": "UNDECIDED", "candidates": [list(c) for c in cands], "time": round(time.time() - t0, 1)}


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("n", type=int); ap.add_argument("blocks"); ap.add_argument("--candidates", type=int, default=6)
    a = ap.parse_args()
    blocks = [sorted(map(int, b.split(","))) for b in a.blocks.split()]
    import json
    print(json.dumps(prove(a.n, blocks, a.candidates), indent=1))
